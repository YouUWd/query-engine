package com.example.schoolquery.mutation;

import com.example.schoolquery.metadata.MetadataRegistry;
import com.example.schoolquery.model.SysModule;
import com.example.schoolquery.model.SysModuleField;
import com.example.schoolquery.model.SysTableRelation;
import com.example.schoolquery.relation.RelationResolver;
import org.h2.jdbcx.JdbcDataSource;
import org.jooq.DSLContext;
import org.jooq.SQLDialect;
import org.jooq.impl.DSL;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.*;

class AggregateMutationExecutorTest {
    private MetadataRegistry registry() {
        List<SysModule> modules = List.of(
                new SysModule(1L, null, "student", "学生", false),
                new SysModule(2L, 1L, "student_course", "课程", false),
                new SysModule(3L, 2L, "course_item", "课程项目", false));
        List<SysModuleField> fields = List.of(
                new SysModuleField(101L, 1L, "student", "id", "ID"),
                new SysModuleField(102L, 1L, "student", "name", "姓名"),
                new SysModuleField(201L, 2L, "student_course", "id", "ID"),
                new SysModuleField(202L, 2L, "student_course", "student_id", "学生ID"),
                new SysModuleField(203L, 2L, "student_course", "course_name", "课程"),
                new SysModuleField(301L, 3L, "course_item", "id", "ID"),
                new SysModuleField(302L, 3L, "course_item", "course_id", "课程ID"),
                new SysModuleField(303L, 3L, "course_item", "item_name", "项目"));
        List<SysTableRelation> relations = List.of(
                new SysTableRelation(1L, "student", "id", "student_course", "student_id", SysTableRelation.RelationType.ONE_TO_MANY),
                new SysTableRelation(2L, "student_course", "id", "course_item", "course_id", SysTableRelation.RelationType.ONE_TO_MANY));
        return new MetadataRegistry(modules, fields, relations);
    }

    private DSLContext dsl() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:aggregate;MODE=MySQL;DB_CLOSE_DELAY=-1");
        try (Connection c = ds.getConnection()) {
            c.createStatement().execute("DROP ALL OBJECTS");
            c.createStatement().execute("CREATE TABLE student(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))");
            c.createStatement().execute("CREATE TABLE student_course(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT, course_name VARCHAR(100))");
            c.createStatement().execute("CREATE TABLE course_item(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, course_id BIGINT, item_name VARCHAR(100))");
            c.createStatement().execute("INSERT INTO student(id,name) VALUES (1,'Alice')");
            c.createStatement().execute("INSERT INTO student_course(id,student_id,course_name) VALUES (10,1,'Math'),(11,1,'Java')");
            c.createStatement().execute("INSERT INTO course_item(id,course_id,item_name) VALUES (100,10,'JDBC'),(101,10,'SQL'),(102,11,'Spring')");
            c.createStatement().execute("ALTER TABLE student ALTER COLUMN id RESTART WITH 1000");
            c.createStatement().execute("ALTER TABLE student_course ALTER COLUMN id RESTART WITH 2000");
            c.createStatement().execute("ALTER TABLE course_item ALTER COLUMN id RESTART WITH 3000");
        }
        return DSL.using(ds, SQLDialect.H2);
    }

    private AggregateMutationExecutor executor() { return new AggregateMutationExecutor(registry(), new RelationResolver(registry())); }

    @Test
    void generatedKeysPropagateThreeLevels() throws Exception {
        AggregateMutation mutation = new AggregateMutation(AggregateMutation.Operation.INSERT, 1,
                Map.of("f102", "Bob"), List.of(new AggregateMutation(AggregateMutation.Operation.INSERT, 2,
                        Map.of("f203", "Java"), List.of(new AggregateMutation(AggregateMutation.Operation.INSERT, 3,
                                Map.of("f303", "JDBC"), List.of(), AggregateMutation.SaveMode.PATCH, false, "item")),
                        AggregateMutation.SaveMode.PATCH, false, "course")),
                AggregateMutation.SaveMode.PATCH, false, "student");
        AggregateMutationResult result = executor().executeWithResult(dsl(), mutation);
        assertEquals(3, result.affectedRows());
        assertEquals(3, result.generatedKeys().size());
        assertEquals(result.generatedKeys().get(0), result.generatedKeysByClientKey().get("student"));
        assertEquals(result.generatedKeys().get(1), result.generatedKeysByClientKey().get("course"));
        assertEquals(result.generatedKeys().get(2), result.generatedKeysByClientKey().get("item"));
    }

    @Test
    void fullSyncRemovesOmittedChildrenAndNestedOrphans() throws Exception {
        AggregateMutation mutation = new AggregateMutation(AggregateMutation.Operation.UPDATE, 1,
                Map.of("f101", 1),
                List.of(new AggregateMutation(AggregateMutation.Operation.UPDATE, 2,
                        Map.of("f201", 10, "f203", "Java"),
                        List.of(new AggregateMutation(AggregateMutation.Operation.UPDATE, 3,
                                Map.of("f301", 100, "f303", "JDBC-2"), List.of(),
                                AggregateMutation.SaveMode.FULL_SYNC, true)),
                        AggregateMutation.SaveMode.FULL_SYNC, true)),
                AggregateMutation.SaveMode.FULL_SYNC, true);
        DSLContext dsl = dsl();
        executor().execute(dsl, mutation);
        assertEquals(1, dsl.fetchCount(DSL.table("student_course"), DSL.field("student_id").eq(1)));
        assertEquals(0, dsl.fetchCount(DSL.table("student_course"), DSL.field("id").eq(11)));
        assertEquals("JDBC-2", dsl.select(DSL.field("item_name")).from(DSL.table("course_item")).where(DSL.field("id").eq(100)).fetchOne(DSL.field("item_name")));
        assertEquals(1, dsl.fetchCount(DSL.table("course_item"), DSL.field("course_id").eq(10)));
        assertEquals(0, dsl.fetchCount(DSL.table("course_item"), DSL.field("id").eq(101)));
    }

    @Test
    void fullSyncCanExplicitlyClearAnEmptyChildCollection() throws Exception {
        AggregateMutation mutation = new AggregateMutation(AggregateMutation.Operation.UPDATE, 1,
                Map.of("f101", 1), List.of(), AggregateMutation.SaveMode.FULL_SYNC, true, Set.of(2L));
        DSLContext dsl = dsl();
        assertEquals(3, executor().execute(dsl, mutation));
        assertEquals(0, dsl.fetchCount(DSL.table("student_course"), DSL.field("student_id").eq(1)));
        assertEquals(0, dsl.fetchCount(DSL.table("course_item"), DSL.field("course_id").in(10, 11)));
    }

    @Test
    void deleteCascadesBottomUp() throws Exception {
        AggregateMutation mutation = new AggregateMutation(AggregateMutation.Operation.DELETE, 1,
                Map.of("f101", 1), List.of(), AggregateMutation.SaveMode.PATCH, false);
        DSLContext dsl = dsl();
        assertEquals(6, executor().execute(dsl, mutation));
        assertEquals(0, dsl.fetchCount(DSL.table("student")));
        assertEquals(0, dsl.fetchCount(DSL.table("student_course")));
        assertEquals(0, dsl.fetchCount(DSL.table("course_item")));
    }
}
