package com.example.schoolquery.mutation;

import com.example.schoolquery.metadata.MetadataRegistry;
import com.example.schoolquery.model.RelationType;
import com.example.schoolquery.model.SysModule;
import com.example.schoolquery.model.SysModuleField;
import com.example.schoolquery.model.SysTableRelation;
import com.example.schoolquery.relation.RelationResolver;
import org.jooq.DSLContext;
import org.jooq.SQLDialect;
import org.jooq.impl.DSL;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class AggregateMutationExecutorTest {
    private MetadataRegistry registry() {
        return new MetadataRegistry(
                List.of(
                        new SysModule(1, "student", "学生", "student", 0),
                        new SysModule(2, "course", "课程", "student_course", 1)
                ),
                List.of(
                        new SysModuleField(101, 1, "student", "id", "ID", 1),
                        new SysModuleField(102, 1, "student", "name", "姓名", 2),
                        new SysModuleField(201, 2, "student_course", "id", "ID", 1),
                        new SysModuleField(202, 2, "student_course", "student_id", "学生ID", 2),
                        new SysModuleField(203, 2, "student_course", "course_name", "课程", 3)
                ),
                List.of(new SysTableRelation(1, "student", "id", "student_course", "student_id", RelationType.ONE_TO_MANY))
        );
    }

    private DSLContext dsl() throws Exception {
        Connection connection = DriverManager.getConnection(
                "jdbc:h2:mem:aggregate_mutation;DATABASE_TO_UPPER=FALSE;DB_CLOSE_DELAY=-1");
        connection.createStatement().execute("drop table if exists student_course");
        connection.createStatement().execute("drop table if exists student");
        connection.createStatement().execute(
                "create table student (id int generated by default as identity primary key, name varchar(100))");
        connection.createStatement().execute(
                "create table student_course (id int generated by default as identity primary key, student_id int not null, course_name varchar(100))");
        return DSL.using(connection, SQLDialect.H2);
    }

    @Test
    void insertPropagatesGeneratedParentKeyToAllChildren() throws Exception {
        DSLContext dsl = dsl();
        MetadataRegistry registry = registry();
        AggregateMutation mutation = new AggregateMutation(
                AggregateMutation.Operation.INSERT, 1,
                Map.of("f102", "Alice"),
                List.of(
                        new AggregateMutation(AggregateMutation.Operation.INSERT, 2, Map.of("f203", "Math"), List.of(), AggregateMutation.SaveMode.PATCH, false),
                        new AggregateMutation(AggregateMutation.Operation.INSERT, 2, Map.of("f203", "Java"), List.of(), AggregateMutation.SaveMode.PATCH, false)
                ),
                AggregateMutation.SaveMode.PATCH, false);

        int affected = new AggregateMutationExecutor(registry, new RelationResolver(registry)).execute(dsl, mutation);

        assertEquals(3, affected);
        assertEquals(1, dsl.fetchCount(DSL.table("student")));
        assertEquals(2, dsl.fetchCount(DSL.table("student_course")));
        assertEquals(2, dsl.fetchCount(DSL.table("student_course").where(DSL.field("student_id").eq(1))));
    }

    @Test
    void fullSyncRemovesOnlyOrphansForTheSameChildModule() throws Exception {
        DSLContext dsl = dsl();
        dsl.execute("insert into student(id,name) values (1,'Alice')");
        dsl.execute("insert into student_course(id,student_id,course_name) values (10,1,'Math'),(11,1,'Java'),(12,1,'Physics')");
        MetadataRegistry registry = registry();

        AggregateMutation mutation = new AggregateMutation(
                AggregateMutation.Operation.UPDATE, 1,
                Map.of("f101", 1L, "f102", "Alice Updated"),
                List.of(
                        new AggregateMutation(AggregateMutation.Operation.UPDATE, 2, Map.of("f201", 10L, "f203", "Advanced Math"), List.of(), AggregateMutation.SaveMode.PATCH, false),
                        new AggregateMutation(AggregateMutation.Operation.UPDATE, 2, Map.of("f201", 11L, "f203", "Advanced Java"), List.of(), AggregateMutation.SaveMode.PATCH, false)
                ),
                AggregateMutation.SaveMode.FULL_SYNC, true);

        int affected = new AggregateMutationExecutor(registry, new RelationResolver(registry)).execute(dsl, mutation);

        assertEquals(4, affected);
        assertEquals("Alice Updated", dsl.fetchValue(DSL.field("name"), DSL.table("student"), DSL.field("id").eq(1)));
        assertEquals("Advanced Math", dsl.fetchValue(DSL.field("course_name"), DSL.table("student_course"), DSL.field("id").eq(10)));
        assertEquals("Advanced Java", dsl.fetchValue(DSL.field("course_name"), DSL.table("student_course"), DSL.field("id").eq(11)));
        assertEquals(0, dsl.fetchCount(DSL.table("student_course").where(DSL.field("id").eq(12))));
    }

    @Test
    void deleteCascadesThroughExplicitAggregateChildren() throws Exception {
        DSLContext dsl = dsl();
        dsl.execute("insert into student(id,name) values (1,'Alice')");
        dsl.execute("insert into student_course(id,student_id,course_name) values (10,1,'Math'),(11,1,'Java')");
        MetadataRegistry registry = registry();

        AggregateMutation mutation = new AggregateMutation(
                AggregateMutation.Operation.DELETE, 1,
                Map.of("f101", 1L),
                List.of(
                        new AggregateMutation(AggregateMutation.Operation.DELETE, 2, Map.of("f201", 10L), List.of(), AggregateMutation.SaveMode.PATCH, false),
                        new AggregateMutation(AggregateMutation.Operation.DELETE, 2, Map.of("f201", 11L), List.of(), AggregateMutation.SaveMode.PATCH, false)
                ),
                AggregateMutation.SaveMode.PATCH, false);

        int affected = new AggregateMutationExecutor(registry, new RelationResolver(registry)).execute(dsl, mutation);

        assertEquals(3, affected);
        assertEquals(0, dsl.fetchCount(DSL.table("student")));
        assertEquals(0, dsl.fetchCount(DSL.table("student_course")));
    }
}
